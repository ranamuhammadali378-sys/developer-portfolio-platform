import { describe, it, expect } from '@jest/globals';
import {
  contactSubmissionSchema,
  createProjectSchema,
  updateProfileSchema,
} from '@portfolio/shared';

describe('Enterprise Security, Anti-Spam & Input Validation Suite', () => {
  describe('1. Contact Form Anti-Spam & Phone Validation', () => {
    it('accepts a valid verified client inquiry with phone number', () => {
      const result = contactSubmissionSchema.safeParse({
        senderName: 'Rana Muhammad Ali',
        senderEmail: 'client@example.com',
        senderPhone: '+92 300 1234567',
        subject: 'Full-Stack Web & Flutter Project',
        message: 'We would like to discuss a scalable software engineering project.',
      });
      expect(result.success).toBe(true);
    });

    it('blocks submissions with invalid phone number formats or XSS payloads', () => {
      const result = contactSubmissionSchema.safeParse({
        senderName: 'Attacker',
        senderEmail: 'bad@example.com',
        senderPhone: '<script>alert(1)</script>',
        subject: 'Test Subject',
        message: 'Trying to inject script tags inside phone field.',
      });
      expect(result.success).toBe(false);
    });

    it('traps automated spam bots filling the hidden honeypot field', () => {
      const result = contactSubmissionSchema.safeParse({
        senderName: 'Spam Bot',
        senderEmail: 'bot@spam.com',
        senderPhone: '+923001112233',
        subject: 'Buy cheap links',
        message: 'Automated spam message generated by a bot script.',
        websiteHoneypot: 'http://spam-site.com',
      });
      expect(result.success).toBe(false);
    });
  });

  describe('2. Project & Profile Strict Schema Enforcement', () => {
    it('blocks invalid or javascript: protocol URLs in projects', () => {
      const result = createProjectSchema.safeParse({
        title: 'Malicious Link Test',
        summary: 'Testing protocol injection protection in project links.',
        description: 'Detailed description with at least twenty characters.',
        category: 'Full-Stack',
        technologies: ['Next.js', 'Node.js'],
        liveUrl: 'javascript:alert(document.cookie)',
        projectDate: '2026-11',
      });
      expect(result.success).toBe(false);
    });

    it('accepts valid BS Software Engineer profile updates', () => {
      const result = updateProfileSchema.safeParse({
        fullName: 'Rana Muhammad Ali',
        headline: 'BS Software Engineer | Full-Stack & Flutter Architect',
        animatedRoles: ['BS Software Engineer', 'Flutter Mobile Developer'],
        shortBio: 'BS Software Engineer building scalable mobile and full-stack web systems.',
        detailedBio:
          'BS Software Engineer from COMSATS University Islamabad, Vehari Campus, focused on secure RESTful APIs and cross-platform apps.',
        careerObjective: 'Engineering resilient, secure, and scalable software platforms.',
        interests: ['Full-Stack Architecture', 'Mobile Development'],
        location: 'Pakistan',
        email: 'ranamuhammadali378@gmail.com',
        availabilityStatus: 'Open to Software Engineering Roles',
      });
      expect(result.success).toBe(true);
    });
  });
});